/**
 * Tahseel schema (BUILD_PLAN §5). M0 lands the foundation tables plus debtors
 * and invoices so the generic RLS isolation test runs against real business
 * tables from day one. Remaining §5 tables arrive with their milestones.
 * Domain tables: id uuid v7, created_at, updated_at, tenant_id (see ADR-007
 * for the Better Auth table exception).
 */
const id = () => uuid("id").primaryKey().$defaultFn(() => uuidv7());
const createdAt = () => timestamp("created_at", { withTimezone: true }).notNull().defaultNow();
const updatedAt = () => timestamp("updated_at", { withTimezone: true }).notNull().defaultNow();
const tenantId = () => uuid("tenant_id").notNull().references(() => tenants.id, { onDelete: "cascade" });

// ---------------------------------------------------------------- tenants
export interface TenantSettings {
  quietStart: string;
  quietEnd: string;
  fridayMorningSkip: boolean;
  autoCloseEnabled: boolean;
  defaultChannel: "whatsapp" | "sms";
  tone: "polite" | "firm";
  defaultTermsDays: number;
  easternDigits: boolean;
  /** Merchant Profile & Localization */
  businessNameEn?: string;
  taxId?: string;
  currency?: "EGP" | "SAR" | "USD" | "AED" | "EUR" | "KWD";
  exportLanguage?: "ar" | "en";
  /** F4: kill switch (manual, or quality-guard auto-pause with qualityPausedReason). */
  sendingPaused?: boolean;
  qualityPausedReason?: string;
  /** F4/§6: max reminder messages per debtor per week (default in core). */
  weeklyCap?: number;
  /** F3: fall back to SMS when WhatsApp reports a number unreachable (131026). */
  smsFallbackEnabled?: boolean;
  /** F4: local wall-clock send time for planned steps, "HH:MM" (default 10:00). */
  sendTimeLocal?: string;
  /** F5: merchant opt-in to gateway (Paymob) payments; the provider must also be configured. */
  gatewayEnabled?: boolean;
  /** F10: statement links may be created for debtors (default true). */
  statementLinksEnabled?: boolean;
  /** F10/F5: include the debtor's statement/payment URL in reminders (default false). */
  includePayLinkInReminders?: boolean;
  /** F10: statement link lifetime in days (default 30). */
  statementExpiryDays?: number;
}
