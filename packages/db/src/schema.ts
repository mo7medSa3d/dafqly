export const chequeDirectionEnum = pgEnum("cheque_direction", ["receivable", "payable"]);
export const chequeStatusEnum = pgEnum("cheque_status", ["held", "deposited", "cleared", "bounced", "returned", "cancelled"]);

/**
 * cheques (§5, F9): receivable and payable cheques. Depositing a RECEIVABLE
 * cheque creates a claimed payment (method=cheque) whose id is stored in
 * payment_id; clearing confirms it, bouncing/returning reverses it. The
 * debtor is the counterparty for both directions (§5 keeps debtor_id).
 */
export const cheques = pgTable("cheques", {
  id: id(),
  tenantId: tenantId(),
  debtorId: uuid("debtor_id").notNull().references(() => debtors.id, { onDelete: "restrict" }),
  direction: chequeDirectionEnum("direction").notNull(),
  /** Optional linked invoice the cheque settles (receivable) or pays (payable). */
  invoiceId: uuid("invoice_id").references(() => invoices.id, { onDelete: "restrict" }),
  number: varchar("number", { length: 40 }).notNull(),
  bank: text("bank").notNull(),
  amountMinor: bigint("amount_minor", { mode: "bigint" }).notNull(),
  issueDate: date("issue_date").notNull(),
  dueDate: date("due_date").notNull(),
  status: chequeStatusEnum("status").notNull().default("held"),
  imageFileId: uuid("image_file_id").references(() => files.id, { onDelete: "set null" }),
  /** The claimed payment created at deposit time (receivable only). */
  paymentId: uuid("payment_id").references(() => payments.id, { onDelete: "restrict" }),
  createdAt: createdAt(), updatedAt: updatedAt(),
}, (t) => [
  index("cheques_tenant_due_idx").on(t.tenantId, t.dueDate, t.status),
  index("cheques_tenant_debtor_idx").on(t.tenantId, t.debtorId),
]);

/** cheque_alerts (F9): one row per (cheque, alert kind) — the unique key is what makes the alert job idempotent. */
export const chequeAlerts = pgTable("cheque_alerts", {
  id: id(),
  tenantId: tenantId(),
  chequeId: uuid("cheque_id").notNull().references(() => cheques.id, { onDelete: "cascade" }),
  alertKind: varchar("alert_kind", { length: 20 }).notNull(), // due_in_3_days | due_today
  alertDate: date("alert_date").notNull(),
  createdAt: createdAt(), updatedAt: updatedAt(),
}, (t) => [
  uniqueIndex("cheque_alerts_cheque_kind_uniq").on(t.chequeId, t.alertKind),
  index("cheque_alerts_tenant_idx").on(t.tenantId, t.alertDate),
]);

/**
 * plans (F13): platform CONFIG, deliberately NOT tenant-owned and NOT under
 * RLS — every tenant reads the same catalogue. Limits are enforced from
 * this table at runtime; it is seeded by migration 0007 from core's
 * PLANS_SEED. price_minor values are PLACEHOLDERS pending HUMAN_INPUTS #10.
 */
export const plans = pgTable("plans", {
  key: varchar("key", { length: 32 }).primaryKey(),
  nameAr: text("name_ar").notNull(),
  nameEn: text("name_en").notNull(),
  monthlyMessageQuota: integer("monthly_message_quota"), // null = unlimited
  priceMinor: bigint("price_minor", { mode: "bigint" }).notNull().default(sql`0`),
  features: jsonb("features").$type<Record<string, unknown>>().notNull().default({}),
  createdAt: createdAt(), updatedAt: updatedAt(),
});

export const subscriptionInvoiceStatusEnum = pgEnum("subscription_invoice_status", ["issued", "paid", "void"]);

/** subscription_invoices (F13): one generated invoice per tenant per billing period; unique (tenant, period_start) makes generation idempotent. */
export const subscriptionInvoices = pgTable("subscription_invoices", {
  id: id(),
  tenantId: tenantId(),
  planKey: varchar("plan_key", { length: 32 }).notNull(),
  periodStart: date("period_start").notNull(),
  periodEnd: date("period_end").notNull(),
  amountMinor: bigint("amount_minor", { mode: "bigint" }).notNull(),
  status: subscriptionInvoiceStatusEnum("status").notNull().default("issued"),
  /** Payment provider reference when paid through the provider seam (fake in tests). */
  providerRef: varchar("provider_ref", { length: 128 }),
  createdAt: createdAt(), updatedAt: updatedAt(),
}, (t) => [
  uniqueIndex("subscription_invoices_tenant_period_uniq").on(t.tenantId, t.periodStart),
  index("subscription_invoices_tenant_idx").on(t.tenantId, t.createdAt),
]);

/**
 * notifications: tenant-scoped operational & AI-generated alerts (disputes,
 * receipt claims, human-inbox messages, cheques, overdue spikes, daily AI
 * briefings). Deduplicated per (tenant_id, dedupe_key) so alerts never
 * spam or repeat once created/dismissed.
 */
export const notifications = pgTable("notifications", {
  id: id(),
  tenantId: tenantId(),
  kind: varchar("kind", { length: 40 }).notNull(),
  severity: varchar("severity", { length: 16 }).notNull().default("info"),
  titleAr: text("title_ar").notNull(),
  titleEn: text("title_en").notNull(),
  bodyAr: text("body_ar").notNull(),
  bodyEn: text("body_en").notNull(),
  actionUrl: text("action_url"),
  entityType: varchar("entity_type", { length: 32 }),
  entityId: uuid("entity_id"),
  dedupeKey: varchar("dedupe_key", { length: 160 }).notNull(),
  readAt: timestamp("read_at", { withTimezone: true }),
  dismissedAt: timestamp("dismissed_at", { withTimezone: true }),
  createdAt: createdAt(), updatedAt: updatedAt(),
}, (t) => [
  uniqueIndex("notifications_tenant_dedupe_uniq").on(t.tenantId, t.dedupeKey),
  index("notifications_tenant_unread_idx").on(t.tenantId, t.dismissedAt, t.readAt, t.createdAt),
]);

/**
 * tenant_deletions (M6, ADR-024): the platform-level TOMBSTONE left behind
 * when a tenant deletes all its data (§8 delete-tenant-data). Deliberately
 * NOT a tenant table: it must survive the tenant's deletion, so it has no
 * tenant_id and no RLS — it holds only the tenant's name snapshot, who
 * deleted it, when, and per-table row counts. Written and read ONLY through
 * the owner connection by the tenant-data service.
 */
export const tenantDeletions = pgTable("tenant_deletions", {
  id: id(),
  tenantName: text("tenant_name").notNull(),
  businessNameAr: text("business_name_ar"),
  deletedByUserId: text("deleted_by_user_id").notNull(),
  rowCounts: jsonb("row_counts").$type<Record<string, number>>().notNull(),
  createdAt: createdAt(),
  updatedAt: updatedAt(),
});

