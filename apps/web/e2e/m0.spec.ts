import { test, expect } from "@playwright/test";
import { mkdirSync, writeFileSync } from "node:fs";

const shotsDir = "e2e/screenshots";
mkdirSync(shotsDir, { recursive: true });

test("M0 exit: sign up → onboarding → empty dashboard in Arabic RTL", async ({ page }) => {
  const email = `e2e-${Date.now()}@example.test`;
  await page.goto("/ar/signup");
  await expect(page.locator("html")).toHaveAttribute("dir", "rtl");
  await expect(page.locator("html")).toHaveAttribute("lang", "ar");
  await page.getByTestId("auth-name").fill("مستخدم تجريبي");
  await page.getByTestId("auth-email").fill(email);
  await page.getByTestId("auth-password").fill("e2e-password-123");
  await page.getByTestId("auth-submit").click();

  await expect(page).toHaveURL(/\/ar\/onboarding/);
  await page.getByTestId("ob-name-ar").fill("محل الاختبار");
  await page.getByTestId("ob-next").click();
  await page.getByTestId("ob-next").click(); // schedule defaults → tone step
  await page.getByTestId("ob-consent").check();
  await page.getByTestId("ob-create").click();

  await expect(page).toHaveURL(/\/ar\/dashboard/);
  await expect(page.getByTestId("dashboard")).toBeVisible();
  await expect(page.getByTestId("empty-state")).toBeVisible();
  await expect(page.getByTestId("kpi-outstanding")).toContainText("0.00");
  await page.screenshot({ path: `${shotsDir}/dashboard-empty-ar-light.png` });
});

test("seeded demo user sees hand-computed totals, no empty state", async ({ page }) => {
  await page.goto("/ar/login");
  await page.getByTestId("auth-email").fill("demo@tahseel.test");
  await page.getByTestId("auth-password").fill("demo-password-123");
  await page.getByTestId("auth-submit").click();
  await expect(page).toHaveURL(/\/ar\/dashboard/);
  // Seed: outstanding = 125,050 + (500,000 − 200,000) piasters = 4,250.50 EGP
  await expect(page.getByTestId("kpi-outstanding")).toContainText("4,250.50");
  await expect(page.getByTestId("kpi-overdue")).toContainText("1,250.50");
  await expect(page.getByTestId("empty-state")).toHaveCount(0);
});

test("brand wiring: manifest is RTL Arabic, theme color is petrol-700, font flag off", async ({ page, request }) => {
  const manifestRes = await request.get("/manifest.webmanifest");
  expect(manifestRes.ok()).toBeTruthy();
  const manifest = (await manifestRes.json()) as { lang: string; dir: string; theme_color: string };
  expect(manifest.lang).toBe("ar");
  expect(manifest.dir).toBe("rtl");
  expect(manifest.theme_color).toBe("#154E5B");

  await page.goto("/ar/login");
  const themeColor = await page.locator('meta[name="theme-color"][media*="light"]').getAttribute("content");
  expect(themeColor).toBe("#154E5B");
  await expect(page.locator("html")).toHaveAttribute("data-brand-font", "off");
});

test("brand evidence: favicon at 16px and dark-mode dashboard screenshots", async ({ page, browser }) => {
  // Favicon legibility at 16px on light and dark browser chrome (BRAND §10):
  // rendered next to a 16px reference box and screenshotted for human review.
  for (const scheme of ["light", "dark"] as const) {
    await page.emulateMedia({ colorScheme: scheme });
    await page.goto("/ar/login");
    await page.setContent(`<body style="background:${scheme === "light" ? "#ffffff" : "#111111"}"><img src="/icon.svg" width="16" height="16"></body>`);
    await page.waitForTimeout(300);
    await page.screenshot({ path: `${shotsDir}/favicon-16-${scheme}.png` });
  }
  // Dark-mode dashboard (demo data) for the BRAND §10 light/dark review.
  const darkContext = await browser.newContext({ colorScheme: "dark", viewport: { width: 390, height: 844 }, locale: "ar-EG" });
  const darkPage = await darkContext.newPage();
  await darkPage.goto("/ar/login");
  await darkPage.getByTestId("auth-email").fill("demo@tahseel.test");
  await darkPage.getByTestId("auth-password").fill("demo-password-123");
  await darkPage.getByTestId("auth-submit").click();
  await expect(darkPage).toHaveURL(/\/ar\/dashboard/);
  await darkPage.screenshot({ path: `${shotsDir}/dashboard-demo-ar-dark.png` });
  await darkContext.close();
  writeFileSync(`${shotsDir}/README.txt`, "Screenshots are human-review evidence (BRAND §10), regenerated by pnpm test:e2e. They are not assertions.\n");
});
